// Built application only; the sole network fault aborts one authenticated PNG GET.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const require = createRequire(new URL("../frontend/package.json", import.meta.url));
const { chromium, expect } = require("@playwright/test");
const fixturePath = process.argv[2];
const fixture = JSON.parse(readFileSync(fixturePath, "utf8"));
const proof = fixture.code_capture;
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
page.setDefaultTimeout(20_000);
let stage = "login", puts = 0, images = 0;
try {
  await page.goto(`${fixture.frontend}/login`);
  await page.getByRole("textbox", { name: "Email" }).fill(fixture.users.admin.email);
  await page.getByLabel("Password", { exact: true }).fill(fixture.users.admin.password);
  await page.getByRole("button", { name: "Sign in to VerboFlex", exact: true }).click();
  await expect(page).not.toHaveURL(/\/login$/);
  stage = "catalog";
  await page.goto(`${fixture.frontend}/products/${proof.product}/strings`);
  await page.getByRole("button", { name: "Code keys", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByText("missing_key", { exact: true })).toBeVisible();
  await expect(dialog.getByText("No imported translation", { exact: true })).toBeVisible();
  await expect(dialog.getByText("java_label", { exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  stage = "context";
  page.on("request", request => {
    if (request.method() === "PUT" && /\/screenshots\//.test(request.url())) puts++;
  });
  await page.goto(`${fixture.frontend}/products/${proof.product}/strings/${proof.group}`);
  await page.getByText("Screenshots and code references", { exact: true }).click();
  const section = page.getByRole("region", { name: "Compose screenshots" });
  await expect(section.getByRole("button", { name: "Generate screenshot", exact: true })).toBeEnabled();
  if (puts !== 0) throw new Error("eager capture");
  await expect(section.getByLabel("Screen preview")).toHaveValue("demo.ScreenPreview");
  stage = "proposal";
  await page.getByRole("button", { name: "Edit translation", exact: true }).click();
  await page.locator('textarea[id^="translation-proposal-"]').first().fill("Saved on demand");
  await expect(section.getByRole("button", { name: "Generate screenshot", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Save translation", exact: true }).click();
  await expect(page.getByRole("region", { name: "Pending proposal" })).toContainText("Saved on demand");
  await expect(section).toContainText("Includes saved proposal version 1.");
  stage = "capture";
  await page.route("**/screenshots/*/image", async route => {
    images++;
    if (images === 1) await route.abort("internetdisconnected");
    else await route.continue();
  });
  const response = page.waitForResponse(r => r.request().method() === "PUT" && /\/screenshots\//.test(r.url()));
  await section.getByRole("button", { name: "Generate screenshot", exact: true }).click();
  const accepted = await response;
  expect(accepted.status()).toBe(202);
  proof.job = (await accepted.json()).id;
  await expect(section).toContainText("Screenshot: succeeded", { timeout: 90_000 });
  stage = "image-reconnect";
  await section.getByRole("button", { name: "Reconnect", exact: true }).click();
  const image = section.getByAltText("Compose screen preview with the selected translations");
  await expect(image).toBeVisible();
  await expect.poll(() => image.evaluate(element => element.complete && element.naturalWidth)).toBe(2);
  expect(images).toBe(2);
  expect(puts).toBe(1);
  stage = "narrow-viewport";
  await page.setViewportSize({ width: 320, height: 720 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: join(fixture.evidence_dir, "code-capture-width320.png"), fullPage: true });
  stage = "reload";
  await page.reload();
  await page.getByText("Screenshots and code references", { exact: true }).click();
  await expect(image).toBeVisible();
  expect(puts).toBe(1);
  proof.browser = { catalog: true, dirty_save_guard: true, image_loaded: true, reconnect: true, reload: true, width320: true };
  writeFileSync(fixturePath, JSON.stringify(fixture), { mode: 0o600 });
} catch (error) {
  writeFileSync(join(fixture.evidence_dir, "code-capture-browser-failure.json"), JSON.stringify({ stage, error: error.name }), { mode: 0o600 });
  await page.screenshot({ path: join(fixture.evidence_dir, "code-capture-failure.png"), fullPage: true });
  throw new Error(`Code capture browser failed at ${stage}`);
} finally {
  await browser.close();
}
